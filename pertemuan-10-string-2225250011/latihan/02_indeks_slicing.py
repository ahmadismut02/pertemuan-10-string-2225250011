# Mengakses karakter individual, substring, dan membalik teks

teks = "Pemrograman"

print("Karakter pertama (indeks 0)  :", teks[0])
print("Karakter terakhir (indeks -1) :", teks[-1])
print("4 Karakter pertama (:4)      :", teks[:4])
print("Karakter indeks 4 sampai akhir:", teks[4:])
print("Teks dibalik (::-1)          :", teks[::-1])
